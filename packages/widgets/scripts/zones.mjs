// Writes src/zones-list.ts from this Node's ICU. 023.
//
// Hermes has no Intl.supportedValuesOf, so the phones read a list checked in
// beside the function that would otherwise ask the runtime. The test in
// apps/core-api/test/zones.test.ts fails when the list and the running Node's
// own differ, and names the zones, so an ICU bump is a rerun of this script
// rather than a zone a phone cannot pick.

import { writeFileSync } from "node:fs";

const zones = Intl.supportedValuesOf("timeZone");
const body = [
  `// Generated by scripts/zones.mjs from Node ${process.version}'s ICU. Do not edit.`,
  "//",
  "// ICU's own spellings, some of them the ones tzdata renamed years ago;",
  "// `knownZones()` in zones.ts maps each through `modernZoneName` on the way out.",
  "",
  "export const KNOWN_ZONES: readonly string[] = [",
  ...zones.map((zone) => `  "${zone}",`),
  "];",
  "",
].join("\n");
writeFileSync(new URL("../src/zones-list.ts", import.meta.url), body);
console.log(`${zones.length} zones written`);
